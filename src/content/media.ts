import type { Localized } from './catalog';
const l = (en: string, fr: string): Localized<string> => ({ en, fr });
export interface PageMedia {
  id: string;
  page: string;
  src: string;
  kind: 'photo' | 'diagram';
  source: string;
  credit: string;
  alt: Localized<string>;
  caption: Localized<string>;
}
const photo = (
  id: string,
  page: string,
  src: string,
  source: string,
  credit: string,
  en: string,
  fr: string,
): PageMedia => ({
  id,
  page,
  src,
  kind: 'photo',
  source,
  credit,
  alt: l(en, fr),
  caption: l(
    'Context photograph. This is not a Ventilators.ca facility or a product offer.',
    'Photo de contexte. Il ne s’agit pas d’un établissement de Ventilators.ca ni d’une offre de produit.',
  ),
});
